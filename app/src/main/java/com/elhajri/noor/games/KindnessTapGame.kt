@Composable
fun KindnessTapGame(onBack: () -> Unit) {
    val context = LocalContext.current
    var progressData by remember {
        mutableStateOf(StageProgressStore.loadProgress(context, GAME_NAME, TOTAL_STAGES))
    }
    var selectedStageIdx by remember { mutableStateOf<Int?>(null) }

    if (selectedStageIdx == null) {
        StageMapScreen(
            gameTitle = "تحدي اللطف والإحسان",
            gameSubtitle = "٢٠ مرحلة لتطبيق الأخلاق والآداب النبوية",
            totalStages = TOTAL_STAGES,
            progressData = progressData,
            onSelectStage = { selectedStageIdx = it },
            onBack = onBack
        )
    } else {
        val stageIdx = selectedStageIdx!!
        KindnessPlayScreen(
            stageIdx = stageIdx,
            totalStages = TOTAL_STAGES,
            onStageComplete = { stars ->
                StageProgressStore.saveProgress(context, GAME_NAME, stageIdx, stars, TOTAL_STAGES)
                progressData = StageProgressStore.loadProgress(context, GAME_NAME, TOTAL_STAGES)
            },
            onNextStage = {
                if (stageIdx + 1 < TOTAL_STAGES) {
                    selectedStageIdx = stageIdx + 1
                } else {
                    selectedStageIdx = null
                }
            },
            onBackToMap = { selectedStageIdx = null }
        )
    }
}

@Composable
private fun KindnessPlayScreen(
    stageIdx: Int,
    totalStages: Int,
    onStageComplete: (Int) -> Unit,
    onNextStage: () -> Unit,
    onBackToMap: () -> Unit
) {
    val stageNumber = stageIdx + 1
    val stageScenarios = remember(stageIdx) {
        val start = stageIdx * 5
        ALL_KINDNESS_SCENARIOS.subList(start, start + 5)
    }

    var scenarioInStageIdx by remember { mutableIntStateOf(0) }
    var selectedOption by remember { mutableStateOf<String?>(null) }
    var isAnswered by remember { mutableStateOf(false) }
    var correctCount by remember { mutableIntStateOf(0) }
    var showWinDialog by remember { mutableStateOf(false) }
    var earnedStars by remember { mutableIntStateOf(3) }

    // Timer shrinks as stages rise (from 10s at stage 1 down to 4.3s at stage 20)
    val roundTimerMs = remember(stageIdx) {
        (10000L - stageIdx * 300L).coerceAtLeast(3500L)
    }

    var timeLeftMillis by remember { mutableLongStateOf(roundTimerMs) }
    var isTimerRunning by remember { mutableStateOf(true) }

    val currentScenario = stageScenarios[scenarioInStageIdx]
    val shuffledOptions = remember(stageIdx, scenarioInStageIdx) {
        currentScenario.options.shuffled()
    }

    LaunchedEffect(scenarioInStageIdx, isTimerRunning, isAnswered) {
        if (isTimerRunning && !isAnswered && !showWinDialog) {
            timeLeftMillis = roundTimerMs
            while (timeLeftMillis > 0 && isTimerRunning && !isAnswered) {
                delay(100L)
                timeLeftMillis -= 100L
            }
            if (timeLeftMillis <= 0 && !isAnswered) {
                isAnswered = true
                selectedOption = null
            }
        }
    }

    fun handleOptionClick(opt: String) {
        if (isAnswered) return
        selectedOption = opt
        isAnswered = true
        isTimerRunning = false

        if (opt == currentScenario.correctResponse) {
            correctCount += 1
        }
    }

    fun nextScenario() {
        if (scenarioInStageIdx + 1 < 5) {
            scenarioInStageIdx += 1
            selectedOption = null
            isAnswered = false
            timeLeftMillis = roundTimerMs
            isTimerRunning = true
        } else {
            // Stage completed!
            val stars = when (correctCount) {
                5 -> 3
                3, 4 -> 2
                else -> 1
            }
            earnedStars = stars
            onStageComplete(stars)
            showWinDialog = true
        }
    }

    Box(
        modifier = Modifier
            .fillMaxSize()
            .themeScreenBackground()
    ) {
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(16.dp)
                .verticalScroll(rememberScrollState())
        ) {
            // Header Bar
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                IconButton(onClick = onBackToMap) {
                    Icon(
                        imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                        contentDescription = "المراحل",
                        tint = Gold
                    )
                }
                Column(horizontalAlignment = Alignment.CenterHorizontally) {
                    Text(
                        text = "تحدي اللطف والإحسان",
                        color = Gold,
                        fontSize = 18.sp,
                        fontWeight = FontWeight.Bold
                    )
                    Text(
                        text = "المرحلة ${stageNumber.toArabicDigits()} من ${totalStages.toArabicDigits()} (موقف ${(scenarioInStageIdx + 1).toArabicDigits()} / ٥)",
                        color = GoldSoft,
                        fontSize = 12.sp
                    )
                }
                Surface(
                    shape = RoundedCornerShape(12.dp),
                    color = NavyCard,
                    border = BorderStroke(1.dp, Gold.copy(alpha = 0.3f))
                ) {
                    Row(
                        modifier = Modifier.padding(horizontal = 8.dp, vertical = 4.dp),
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Icon(
                            imageVector = Icons.Default.Star,
                            contentDescription = null,
                            tint = Gold,
                            modifier = Modifier.size(16.dp)
                        )
                        Spacer(modifier = Modifier.width(4.dp))
                        Text(
                            text = "${correctCount.toArabicDigits()} / ٥",
                            color = Gold,
                            fontSize = 12.sp,
                            fontWeight = FontWeight.Bold
                        )
                    }
                }
            }

            Spacer(modifier = Modifier.height(12.dp))

            // Timer Bar
            val timerProgress = (timeLeftMillis.toFloat() / roundTimerMs.toFloat()).coerceIn(0f, 1f)
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically
            ) {
                Icon(
                    imageVector = Icons.Default.Timer,
                    contentDescription = null,
                    tint = Gold,
                    modifier = Modifier.size(20.dp)
                )
                Spacer(modifier = Modifier.width(8.dp))
                LinearProgressIndicator(
                    progress = { timerProgress },
                    modifier = Modifier
                        .weight(1f)
                        .height(8.dp),
                    color = if (timerProgress > 0.3f) Gold else Color.Red,
                    trackColor = NavyCard
                )
            }

            Spacer(modifier = Modifier.height(16.dp))

            // Situation Card
            Box(
                modifier = Modifier
                    .fillMaxWidth()
                    .noorGlassCard(cornerRadius = 18.dp)
                    .padding(18.dp)
            ) {
                Column {
                    Text(
                        text = "الموقف الأخلاقي:",
                        color = GoldSoft,
                        fontSize = 12.sp,
                        fontWeight = FontWeight.Bold
                    )
                    Spacer(modifier = Modifier.height(6.dp))
                    Text(
                        text = currentScenario.situation,
                        color = TextMain,
                        fontSize = 16.sp,
                        fontWeight = FontWeight.Bold,
                        lineHeight = 22.sp
                    )
                }
            }

            Spacer(modifier = Modifier.height(16.dp))

            // Options
            Column(verticalArrangement = Arrangement.spacedBy(10.dp)) {
                shuffledOptions.forEach { optionText ->
                    val isCorrect = optionText == currentScenario.correctResponse
                    val isSelected = optionText == selectedOption

                    val cardBg = when {
                        !isAnswered -> NavyCard
                        isCorrect -> Color(0xFF2E7D32)
                        isSelected -> Color(0xFFC62828)
                        else -> NavyCard.copy(alpha = 0.5f)
                    }

                    val borderCol = when {
                        !isAnswered -> Gold.copy(alpha = 0.3f)
                        isCorrect -> Color.Green
                        isSelected -> Color.Red
                        else -> Color.Transparent
                    }

                    Surface(
                        shape = RoundedCornerShape(14.dp),
                        color = cardBg,
                        border = BorderStroke(1.dp, borderCol),
                        modifier = Modifier
                            .fillMaxWidth()
                            .clickable(enabled = !isAnswered) { handleOptionClick(optionText) }
                    ) {
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(14.dp),
                            verticalAlignment = Alignment.CenterVertically
                        ) {
                            Text(
                                text = optionText,
                                color = TextMain,
                                fontSize = 14.sp,
                                fontWeight = FontWeight.Medium,
                                modifier = Modifier.weight(1f)
                            )
                            if (isAnswered) {
                                if (isCorrect) {
                                    Icon(
                                        imageVector = Icons.Default.CheckCircle,
                                        contentDescription = null,
                                        tint = Color.Green
                                    )
                                } else if (isSelected) {
                                    Icon(
                                        imageVector = Icons.Default.Close,
                                        contentDescription = null,
                                        tint = Color.Red
                                    )
                                }
                            }
                        }
                    }
                }
            }

            if (isAnswered) {
                Spacer(modifier = Modifier.height(16.dp))

                // Prophetic Manner Banner
                Box(
                    modifier = Modifier
                        .fillMaxWidth()
                        .noorGlassCard(cornerRadius = 14.dp)
                        .padding(14.dp)
                ) {
                    Column {
                        Text(
                            text = "من الهدي النبوي الشريف:",
                            color = Gold,
                            fontSize = 13.sp,
                            fontWeight = FontWeight.Bold
                        )
                        Spacer(modifier = Modifier.height(4.dp))
                        Text(
                            text = currentScenario.propheticManner,
                            color = TextSecondaryLinen,
                            fontSize = 13.sp,
                            lineHeight = 18.sp
                        )
                    }
                }

                Spacer(modifier = Modifier.height(16.dp))

                Button(
                    onClick = { nextScenario() },
                    modifier = Modifier
                        .fillMaxWidth()
                        .height(48.dp),
                    colors = ButtonDefaults.buttonColors(containerColor = Gold),
                    shape = RoundedCornerShape(14.dp)
                ) {
                    Text(
                        text = if (scenarioInStageIdx + 1 < 5) "الموقف التالي" else "إنهاء المرحلة",
                        color = Navy,
                        fontSize = 15.sp,
                        fontWeight = FontWeight.Bold
                    )
                }
            }
        }

        if (showWinDialog) {
            StageWinDialog(
                stageNumber = stageNumber,
                totalStages = totalStages,
                stars = earnedStars,
                stageTitle = "المرحلة ${stageNumber.toArabicDigits()}",
                onNextStage = {
                    showWinDialog = false
                    onNextStage()
                },
                onReplayStage = {
                    showWinDialog = false
                    scenarioInStageIdx = 0
                    selectedOption = null
                    isAnswered = false
                    correctCount = 0
                    timeLeftMillis = roundTimerMs
                    isTimerRunning = true
                },
                onStageMap = onBackToMap
            )
        }
    }
}
